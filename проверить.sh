#!/bin/sh
# Сверяет каждый распакованный файл с его контрольной суммой SHA-256.
# Запускать из корня проекта:  ./проверить.sh
#
# Сам SHA256SUMS.txt в список не входит (нельзя посчитать сумму файла,
# внутри которого она лежит), как и этот скрипт.

cd "$(dirname "$0")" || exit 1

if [ ! -f SHA256SUMS.txt ]; then
  echo "Не найден SHA256SUMS.txt — архив распакован не полностью."
  exit 1
fi

echo "Проверяю $(grep -c . SHA256SUMS.txt) файлов…"
echo

if sha256sum -c --quiet SHA256SUMS.txt; then
  echo
  echo "ВСЁ СОВПАДАЕТ — проект идентичен оригиналу."
  echo "Дальше:  npm install  &&  npm run dev"
  exit 0
fi

echo
echo "ЕСТЬ РАСХОЖДЕНИЯ — файлы выше повреждены или потерялись при переносе."
echo "Распакуйте архив заново."
exit 1
